import { z } from 'zod';

export const createProductSchema = z.object({
  name: z.string().min(1).max(200),
  slug: z.string().min(1).max(200).regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/).optional(),
  description: z.string().min(1),
  priceInCents: z.number().int().positive(),
  supplierCostCents: z.number().int().nonnegative(),
  targetMarginBasisPoints: z.number().int().min(1).max(9999).default(2000),
  pricingTargetType: z.enum(['margin', 'profit']).default('margin'),
  targetProfitCents: z.number().int().nonnegative().nullable().optional(),
  packedWidthCm: z.number().int().min(1).max(300).nullable().optional(),
  packedLengthCm: z.number().int().min(1).max(300).nullable().optional(),
  packedHeightCm: z.number().int().min(1).max(300).nullable().optional(),
  packedWeightGrams: z.number().int().min(1).max(100000).nullable().optional(),
  allowedPaymentMethods: z.array(z.enum(['wompi', 'cash_on_delivery'])).min(1),
  sku: z.string().min(1).max(50),
  stockQuantity: z.number().int().nonnegative().max(100000).default(0),
  status: z.enum(['draft', 'published', 'archived']).default('draft'),
  condition: z.enum(['new', 'used', 'refurbished']).default('new'),
  specifications: z.record(z.unknown()).default({}),
  brand: z.string().max(100).optional(),
  productType: z.string().max(100).optional(),
  tags: z.array(z.string()).default([]),
  guideTitle: z.string().trim().max(140).optional(),
  guideContent: z.string().max(12000).optional(),
  relatedBlogPostIds: z.array(z.string().uuid()).max(20).default([]),
  barcodeGtin: z.string().max(50).optional(),
  seoTitle: z.string().max(100).optional(),
  seoDescription: z.string().max(300).optional(),
  canonicalUrl: z.string().url().optional(),
  ogImageId: z.string().optional(),
  noindex: z.boolean().default(false),
  electronicInvoiceEnabled: z.boolean().default(false),
  allowsCashOnDelivery: z.boolean().default(true),
  shippingScope: z.enum(['national', 'local']).default('national'),
  localCoverageZones: z.array(z.string()).default([]),
  saleMode: z.enum(['cash', 'credit', 'both']).default('cash'),
  categoryIds: z.array(z.string()).default([]),
  mediaIds: z.array(z.string()).default([]),
}).strict();

